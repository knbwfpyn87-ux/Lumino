// Builds the classes from src/lib/courses/content/*.ts (Lumino course format, see src/lib/courses/dsl.ts).
//   src/lib/courses/curriculum.gen.ts   outline + practice data (titles, terms, quick checks, generators) — loads with the app
//   src/lib/courses/lessons/*.gen.ts    lesson text for one class — loads when a lesson is opened
// Fails on any formatting mistake or lint problem.  Run: npm run courses   (also runs before every build)
import { readdirSync, writeFileSync, mkdirSync, readFileSync, existsSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseCourse, lintCourse, type CourseSrc } from '../src/lib/courses/dsl';
import { GENS } from '../src/lib/courses/registry';

const DIR = 'src/lib/courses/content'; const OUT = 'src/lib/courses/lessons';
const files = readdirSync(DIR).filter(f => f.endsWith('.ts')).sort();
const courses: CourseSrc[] = []; const problems: string[] = [];
for (const f of files) {
  const text = (await import(pathToFileURL(join(process.cwd(), DIR, f)).href)).default as string;
  try { const c = parseCourse(text, join(DIR, f)); if (c.id !== f.replace(/\.ts$/, '')) problems.push(`${f}: @course id "${c.id}" must match the file name`); courses.push(c); problems.push(...lintCourse(c, new Set(Object.keys(GENS)))); }
  catch (e) { problems.push((e as Error).message); }
}
// Science classes get a virtual lab and math classes a real-world demo in every unit.
const SCIENCE = new Set(['ib-physics', 'ib-chem', 'ib-bio', 'ib-ess', 'gen-chem', 'univ-physics', 'college-bio', 'act-science']);
const MATH = new Set(['ib-math-aa', 'ib-math-ai', 'college-calc1', 'college-calc2', 'college-stats', 'sat-math', 'act-math']);
const missing: string[] = [];
for (const c of courses) {
  const kind = c.category === 'Science' || SCIENCE.has(c.id) ? 'lab' : c.category === 'Math' || MATH.has(c.id) ? 'demo' : null;
  if (!kind) continue;
  c.units.forEach((u, ui) => { if (!u.lessons.some(l => l.blocks.some(b => b.t === 'lab' && b.kind === kind))) missing.push(`${c.id} unit ${ui + 1}: needs a ${kind}:`); });
}
problems.push(...missing);
if (problems.length) { console.error(problems.map(p => '✗ ' + p).join('\n')); process.exit(1); }

const header = '// GENERATED by scripts/build-courses.ts from src/lib/courses/content — edit those files, then run: npm run courses\n';
const write = (path: string, body: string) => { const next = header + body; if (!existsSync(path) || readFileSync(path, 'utf8') !== next) writeFileSync(path, next); };

const curriculum = courses.map(c => ({ id: c.id, name: c.name, level: c.level, emoji: c.emoji, category: c.category, subject: c.subject,
  units: c.units.map(u => ({ title: u.title, summary: u.summary, lessons: u.lessons.map(l => { const lab = l.blocks.find(b => b.t === 'lab'); return { title: l.title, gens: l.gens, terms: l.terms, checks: l.checks, ...(lab && lab.t === 'lab' ? { lab: lab.kind } : {}) }; }) })) }));
write('src/lib/courses/curriculum.gen.ts', `import type { CurriculumCourse } from './types';\nexport const CURRICULUM: CurriculumCourse[] = ${JSON.stringify(curriculum)};\n`);

mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) if (f.endsWith('.gen.ts') && f !== 'index.gen.ts' && !courses.some(c => `${c.id}.gen.ts` === f)) rmSync(join(OUT, f));
for (const c of courses) write(join(OUT, `${c.id}.gen.ts`), `import type { LessonText } from '../types';\nconst text: LessonText[][] = ${JSON.stringify(c.units.map(u => u.lessons.map(l => ({ say: l.say, blocks: l.blocks }))))};\nexport default text;\n`);
write(join(OUT, 'index.gen.ts'), `import type { LessonText } from '../types';\nexport const LESSON_TEXT: Record<string, () => Promise<{ default: LessonText[][] }>> = {\n${courses.map(c => `  '${c.id}': () => import('./${c.id}.gen'),`).join('\n')}\n};\n`);

const n = (f: (c: CourseSrc) => number) => courses.reduce((s, c) => s + f(c), 0);
console.log(`✓ ${courses.length} classes · ${n(c => c.units.length)} units · ${n(c => c.units.reduce((s, u) => s + u.lessons.length, 0))} lessons · ${n(c => c.units.reduce((s, u) => s + u.lessons.reduce((t, l) => t + l.checks.length, 0), 0))} quick checks · ${n(c => c.units.reduce((s, u) => s + u.lessons.reduce((t, l) => t + l.blocks.filter(b => b.t === 'lab').length, 0), 0))} labs and demos`);
